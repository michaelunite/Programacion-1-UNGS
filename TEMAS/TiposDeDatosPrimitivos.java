package TEMAS;

public class TiposDeDatosPrimitivos {
    public static void main(String[] args) {

        // Tipos de datos primitivos en Java

        // tipo de dato entero
        int entero = 10;
        System.out.println("Valor de la variable entero es : " + entero);

        // tipo de dato decimal
        double decimal = 3.14;
        System.out.println("Valor de la variable decimal es : " + decimal);

        // tipo de dato booleano
        boolean esVerdadero = true;
        System.out.println("Valor de la variable esVerdadero es : " + esVerdadero);

        // el tipo de dato booleano solo puede tener dos valores posibles: true (verdadero) o false (falso). Se utiliza para representar condiciones lógicas y tomar decisiones en el flujo del programa.

        // tipo de dato caracter
        char caracter = 'A';
        System.out.println("Valor de la variable caracter es : " + caracter);
        
        // el tipo de dato char se utiliza para representar un solo carácter, como una letra, un número o un símbolo. Se define utilizando comillas simples (' ') y puede almacenar cualquier carácter Unicode.

    }
}

